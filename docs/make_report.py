def set_cell_background(cell, color: str) -> None:
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), color)
    cell._tc.get_or_add_tcPr().append(shd)


def add_field(paragraph, instruction: str) -> None:
    run = paragraph.add_run()
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = instruction
    separate = OxmlElement("w:fldChar")
    separate.set(qn("w:fldCharType"), "separate")
    text = OxmlElement("w:t")
    text.text = "..."
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    for element in (begin, instr, separate, text, end):
        run._r.append(element)


def configure_styles(document: Document) -> None:
    normal = document.styles["Normal"]
    normal.font.name = BODY_FONT
    normal.font.size = Pt(14)
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), BODY_FONT)
    paragraph_format = normal.paragraph_format
    paragraph_format.line_spacing = 1.5
    paragraph_format.space_after = Pt(0)
    paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    paragraph_format.first_line_indent = Cm(1.25)

    for name, size, before, after in (
        ("Heading 1", 16, 18, 10),
        ("Heading 2", 14, 12, 6),
        ("Heading 3", 14, 10, 4),
    ):
        style = document.styles[name]
        style.font.name = BODY_FONT
        style.font.size = Pt(size)
        style.font.bold = True
        style.font.color.rgb = ACCENT
        style.paragraph_format.space_before = Pt(before)
        style.paragraph_format.space_after = Pt(after)
        style.paragraph_format.first_line_indent = Cm(0)
        style.paragraph_format.line_spacing = 1.15
        style.paragraph_format.keep_with_next = True

    for name in ("List Bullet", "List Number"):
        style = document.styles[name]
        style.font.name = BODY_FONT
        style.font.size = Pt(13)
        style.paragraph_format.line_spacing = 1.15
        style.paragraph_format.space_after = Pt(4)
        style.paragraph_format.first_line_indent = Cm(0)
        style.paragraph_format.left_indent = Cm(1.0)


def setup_page(document: Document) -> None:
    section = document.sections[0]
    section.left_margin = Cm(3.0)
    section.right_margin = Cm(1.5)
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(2.0)

    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer.paragraph_format.first_line_indent = Cm(0)
    add_field(footer, " PAGE ")
    for run in footer.runs:
        run.font.name = BODY_FONT
        run.font.size = Pt(11)


class Report:
    def __init__(self) -> None:
        self.doc = Document()
        configure_styles(self.doc)
        setup_page(self.doc)

    # -- text helpers ------------------------------------------------------

    def para(self, text: str = "", *, indent: bool = True,
             align=WD_ALIGN_PARAGRAPH.JUSTIFY, size: int | None = None,
             bold: bool = False, italic: bool = False, space_after: int = 6):
        p = self.doc.add_paragraph()
        p.paragraph_format.alignment = align
        p.paragraph_format.first_line_indent = Cm(1.25 if indent else 0)
        p.paragraph_format.space_after = Pt(space_after)
        run = p.add_run(text)
        run.bold = bold
        run.italic = italic
        if size:
            run.font.size = Pt(size)
        return p

    def rich(self, chunks, *, indent: bool = True, space_after: int = 6):
        """chunks: list of (text, bold) tuples."""
        p = self.doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(1.25 if indent else 0)
        p.paragraph_format.space_after = Pt(space_after)
        for text, bold in chunks:
            run = p.add_run(text)
            run.bold = bold
        return p

    def h1(self, text: str):
        return self.doc.add_heading(text, level=1)

    def h2(self, text: str):
        return self.doc.add_heading(text, level=2)

    def bullets(self, items, numbered: bool = False):
        style = "List Number" if numbered else "List Bullet"
        for item in items:
            p = self.doc.add_paragraph(style=style)
            if isinstance(item, tuple):
                head, tail = item
                run = p.add_run(head)
                run.bold = True
                p.add_run(tail)
            else:
                p.add_run(item)

    def code(self, text: str, size: int = 9):
        p = self.doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.left_indent = Cm(0.6)
        p.paragraph_format.space_before = Pt(4)
        p.paragraph_format.space_after = Pt(8)
        p.paragraph_format.line_spacing = 1.0
        run = p.add_run(text)
        run.font.name = MONO_FONT
        run.font.size = Pt(size)
        run._element.rPr.rFonts.set(qn("w:eastAsia"), MONO_FONT)
        return p

    def figure(self, filename, caption: str, width_cm: float = 14.0):
        path = Path(filename)
        if not path.is_absolute():
            path = PLOTS / path
        if not path.is_file():
            raise FileNotFoundError(path)
        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.space_before = Pt(8)
        p.paragraph_format.space_after = Pt(2)
        p.add_run().add_picture(str(path), width=Cm(width_cm))
        c = self.doc.add_paragraph()
        c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        c.paragraph_format.first_line_indent = Cm(0)
        c.paragraph_format.space_after = Pt(12)
        c.paragraph_format.line_spacing = 1.0
        run = c.add_run(caption)
        run.italic = True
        run.font.size = Pt(11)
        return p

    def caption(self, text: str):
        p = self.doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(10)
        p.paragraph_format.line_spacing = 1.0
        run = p.add_run(text)
        run.italic = True
        run.font.size = Pt(11)
        return p

    def table(self, header, rows, widths=None, font_size: int = 11):
        table = self.doc.add_table(rows=1, cols=len(header))
        table.style = "Table Grid"
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        head_cells = table.rows[0].cells
        for i, title in enumerate(header):
            head_cells[i].text = ""
            p = head_cells[i].paragraphs[0]
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.line_spacing = 1.0
            run = p.add_run(title)
            run.bold = True
            run.font.size = Pt(font_size)
            set_cell_background(head_cells[i], "DCE6F1")
        for row in rows:
            cells = table.add_row().cells
            for i, value in enumerate(row):
                cells[i].text = ""
                p = cells[i].paragraphs[0]
                p.paragraph_format.first_line_indent = Cm(0)
                p.paragraph_format.space_after = Pt(0)
                p.paragraph_format.line_spacing = 1.0
                run = p.add_run(str(value))
                run.font.size = Pt(font_size)
        if widths:
            for row in table.rows:
                for i, width in enumerate(widths):
                    row.cells[i].width = Cm(width)
        self.doc.add_paragraph().paragraph_format.space_after = Pt(0)
        return table


