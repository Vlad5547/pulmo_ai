def configure(document):
    normal = document.styles["Normal"]
    normal.font.name = FONT
    normal.font.size = Pt(14)
    normal.font.color.rgb = RGBColor(0, 0, 0)
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    pf = normal.paragraph_format
    pf.line_spacing = 1.5
    pf.space_after = Pt(0)
    pf.space_before = Pt(0)
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf.first_line_indent = INDENT

    section = document.sections[0]
    section.left_margin = Cm(2.5)
    section.right_margin = Cm(1.5)
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(2.0)

    header = section.header.paragraphs[0]
    header.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    header.paragraph_format.first_line_indent = Cm(0)
    run = header.add_run()
    for tag, attrs, text in (
        ("w:fldChar", {"w:fldCharType": "begin"}, None),
        ("w:instrText", {"xml:space": "preserve"}, " PAGE "),
        ("w:fldChar", {"w:fldCharType": "separate"}, None),
        ("w:t", {}, "1"),
        ("w:fldChar", {"w:fldCharType": "end"}, None),
    ):
        el = OxmlElement(tag)
        for key, value in attrs.items():
            el.set(qn(key), value)
        if text is not None:
            el.text = text
        run._r.append(el)
    run.font.name = FONT
    run.font.size = Pt(12)


class Ch:
    def __init__(self):
        self.doc = Document()
        configure(self.doc)
        self.fig_no = 0
        self.tab_no = 0

    # text ----------------------------------------------------------------
    def p(self, text="", indent=True, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
          bold=False, italic=False, size=None, after=0):
        par = self.doc.add_paragraph()
        par.paragraph_format.alignment = align
        par.paragraph_format.first_line_indent = INDENT if indent else Cm(0)
        par.paragraph_format.space_after = Pt(after)
        run = par.add_run(text)
        run.bold = bold
        run.italic = italic
        run.font.name = FONT
        if size:
            run.font.size = Pt(size)
        return par

    def chapter_title(self, text):
        return self.p(text, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER,
                      bold=True, after=18)

    def h2(self, text):
        if self.doc.paragraphs and self.doc.paragraphs[-1].text.strip():
            self.p("", indent=False)
        par = self.p(text, bold=True, after=6)
        par.paragraph_format.keep_with_next = True
        return par

    def h3(self, text):
        par = self.p(text, italic=True, after=6)
        par.paragraph_format.keep_with_next = True
        return par

    def bullet(self, text):
        par = self.doc.add_paragraph(style="List Bullet")
        par.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        par.paragraph_format.first_line_indent = Cm(0)
        par.paragraph_format.left_indent = INDENT
        par.paragraph_format.line_spacing = 1.5
        par.paragraph_format.space_after = Pt(0)
        run = par.add_run(text)
        run.font.name = FONT
        run.font.size = Pt(14)
        return par

    # formulas ------------------------------------------------------------
    def _blank(self):
        par = self.doc.add_paragraph()
        par.paragraph_format.first_line_indent = Cm(0)
        par.paragraph_format.space_after = Pt(0)
        par.paragraph_format.line_spacing = 1.5
        return par

    def formula(self, body, number):
        self._blank()
        par = self.doc.add_paragraph()
        pf = par.paragraph_format
        pf.first_line_indent = Cm(0)
        pf.space_before = Pt(0)
        pf.space_after = Pt(0)
        pf.line_spacing = 1.5
        pf.tab_stops.add_tab_stop(Cm(TEXT_WIDTH_CM / 2), WD_TAB_ALIGNMENT.CENTER)
        pf.tab_stops.add_tab_stop(Cm(TEXT_WIDTH_CM), WD_TAB_ALIGNMENT.RIGHT)
        run = par.add_run("\t" + body + "\t(" + number + ")")
        run.font.name = FONT
        run.font.size = Pt(14)
        run.italic = True
        self._blank()
        return par

    def where(self, lines):
        self.p("де", indent=False)
        for line in lines:
            par = self.p(line, indent=False)
            par.paragraph_format.left_indent = INDENT

    # figures / tables -----------------------------------------------------
    def figure(self, filename, caption, width_cm=15.5):
        par = self.doc.add_paragraph()
        par.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
        par.paragraph_format.first_line_indent = Cm(0)
        par.paragraph_format.space_before = Pt(6)
        par.paragraph_format.keep_with_next = True
        par.add_run().add_picture(str(FIGS / filename), width=Cm(width_cm))
        self.fig_no += 1
        cap = self.p("Рис. 1.%d. %s" % (self.fig_no, caption), indent=False,
                     align=WD_ALIGN_PARAGRAPH.CENTER, size=13, after=10)
        cap.paragraph_format.line_spacing = 1.0
        return cap

    def table(self, caption, header, rows, widths=None):
        self.tab_no += 1
        cap = self.p("Таблиця 1.%d" % self.tab_no, indent=False,
                     align=WD_ALIGN_PARAGRAPH.RIGHT, size=13)
        cap.paragraph_format.line_spacing = 1.0
        cap.paragraph_format.keep_with_next = True
        title = self.p(caption, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER,
                       bold=True, size=13, after=4)
        title.paragraph_format.line_spacing = 1.0
        title.paragraph_format.keep_with_next = True

        tbl = self.doc.add_table(rows=1, cols=len(header))
        tbl.style = "Table Grid"
        for cell, text in zip(tbl.rows[0].cells, header):
            cell.text = ""
            par = cell.paragraphs[0]
            par.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
            par.paragraph_format.first_line_indent = Cm(0)
            par.paragraph_format.line_spacing = 1.0
            par.paragraph_format.space_after = Pt(0)
            run = par.add_run(text)
            run.bold = True
            run.font.name = FONT
            run.font.size = Pt(11)
        for row in rows:
            cells = tbl.add_row().cells
            for cell, text in zip(cells, row):
                cell.text = ""
                par = cell.paragraphs[0]
                par.paragraph_format.first_line_indent = Cm(0)
                par.paragraph_format.line_spacing = 1.0
                par.paragraph_format.space_after = Pt(0)
                run = par.add_run(text)
                run.font.name = FONT
                run.font.size = Pt(11)
        if widths:
            for row in tbl.rows:
                for cell, width in zip(row.cells, widths):
                    cell.width = Cm(width)

        # шапку повторювати на кожній сторінці, рядок не розривати,
        # таблицю тримати цілою (щоб не знадобилось «Продовження таблиці»)
        tr_pr = tbl.rows[0]._tr.get_or_add_trPr()
        tr_pr.append(OxmlElement("w:tblHeader"))
        for row in tbl.rows:
            row._tr.get_or_add_trPr().append(OxmlElement("w:cantSplit"))
        for row in tbl.rows[:-1]:
            for cell in row.cells:
                for par in cell.paragraphs:
                    par.paragraph_format.keep_with_next = True
        self.p("", indent=False, after=6)
        return tbl

    def save(self):
        self.doc.save(OUT)


