def build_references(c):
    c.doc.add_page_break()
    c.p("СПИСОК ВИКОРИСТАНИХ ДЖЕРЕЛ", indent=False,
        align=WD_ALIGN_PARAGRAPH.CENTER, bold=True, after=12)
    for i, ref in enumerate(REFERENCES, start=1):
        par = c.p("%d. %s" % (i, ref), indent=False, size=13)
        par.paragraph_format.left_indent = Cm(0.75)
        par.paragraph_format.first_line_indent = Cm(-0.75)
        par.paragraph_format.line_spacing = 1.5
        par.paragraph_format.space_after = Pt(2)


