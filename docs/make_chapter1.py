def _box(ax, x, y, w, h, text, fc="#eef3f8", ec="#2b4c6f", fs=9):
    ax.add_patch(
        FancyBboxPatch(
            (x, y),
            w,
            h,
            boxstyle="round,pad=0.02,rounding_size=0.06",
            linewidth=1.1,
            facecolor=fc,
            edgecolor=ec,
        )
    )
    ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=fs)


def _arrow(ax, x1, y1, x2, y2):
    ax.add_patch(
        FancyArrowPatch(
            (x1, y1), (x2, y2), arrowstyle="-|>", mutation_scale=11,
            linewidth=1.0, color="#2b4c6f",
        )
    )


def _canvas(w, h):
    fig, ax = plt.subplots(figsize=(w, h), dpi=200)
    ax.set_xlim(0, 10)
    ax.set_ylim(0, h / w * 10)
    ax.axis("off")
    return fig, ax


